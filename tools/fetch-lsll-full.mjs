const OUT = path.join(ROOT, "data", "lsll-one-step");
const CONCURRENCY = Number(process.env.LSLL_CONCURRENCY || 48);
const REQUEST_TIMEOUT_MS = 15000;
const ONLY = new Set(process.argv.slice(2).filter((a) => !a.startsWith("-")));

