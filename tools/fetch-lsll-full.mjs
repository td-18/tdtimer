#!/usr/bin/env node
// Fetch the full one-step LSLL dataset and write one lazy-loaded file per family.
//
//   node tools/fetch-lsll-full.mjs
//   node tools/fetch-lsll-full.mjs ap am f      # only rebuild selected families
//
// CubeRoot's batch pipeline has not filled every family yet. We fetch the
// computed side of each mirror pair and derive the other side by the LSLL
// mirror symmetry (same optimal length; the algorithm is rewritten move by
// move). The enumerated case keys follow CubeRoot's LSLL model:
// 5 corners + 5 edges in 5 positions, canonicalised over pre/post AUF.
//
// The output is data/lsll-one-step/<slug>.js:
//   window.LSLLOneStep["ap"] = [["A+ #<case>", "R U R'"], ...]
//
// The family metadata in data/lsll.js is generated by tools/fetch-lsll.ps1.

