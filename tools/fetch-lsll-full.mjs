const PERMS = (() => {
    const out = [];
    const rec = (prefix, rest) => {
        if (!rest.length) {
            out.push(prefix);
            return;
        }
        for (let i = 0; i < rest.length; i++) {
            rec([...prefix, rest[i]], [...rest.slice(0, i), ...rest.slice(i + 1)]);
        }
    };
    rec([], [0, 1, 2, 3]);
    return out;
})();

function parity(arr) {
    let p = 0;
    for (let i = 0; i < arr.length; i++) {
        for (let j = i + 1; j < arr.length; j++) {
            if (arr[i] > arr[j]) p++;
        }
    }
    return p & 1;
}

function encode(state, l, u) {
    let s = 0;
    let t = 0;
    for (let n = 0; n < 5; n++) {
        const o = n < 4 ? ((n - l + 4) & 3) : 4;
        const c = state.cp[o];
        s = 16 * s + ((c < 4 ? ((c + u) & 3) : 4) * 3 + state.co[o]);
        const e = state.ep[o];
        t = 16 * t + ((e < 4 ? ((e + u) & 3) : 4) * 2 + state.eo[o]);
    }
    return 1048576 * s + t;
}

function canonical(state) {
    let best = Infinity;
    for (let u = 0; u < 4; u++) {
        for (let l = 0; l < 4; l++) {
            const key = encode(state, u, l);
            if (key < best) best = key;
        }
    }
    return best;
}

function decodeState(value) {
    const low = value % 1048576;
    let high = (value - low) / 1048576;
    let rest = low;
    const cp = [];
    const co = [];
    const ep = [];
    const eo = [];
    for (let i = 4; i >= 0; i--) {
        const c = high & 15;
        high >>= 4;
        cp[i] = Math.floor(c / 3);
        co[i] = c % 3;
        const e = rest & 15;
        rest >>= 4;
        ep[i] = e >> 1;
        eo[i] = e & 1;
    }
    return { cp, co, ep, eo };
}

function slotOffset(corner, edge) {
    return corner < 4 ? (4 - corner) & 3 : (edge < 4 ? (edge - corner + 4) & 3 : 0);
}

function positions(kind, c, e, d) {
    const cpos = kind === "CS" || kind === "SS" ? 4 : 0;
    const epos = kind === "ES" || kind === "SS" ? 4 : kind === "TT" ? d : slotOffset(4, e);
    return { cpos, epos };
}

function enumerateCategory(slug, letter, kind, c, e, d) {
    const { cpos, epos } = positions(kind, c, e, d);
    const cornerPos = [0, 1, 2, 3, 4].filter((x) => x !== cpos);
    const edgePos = [0, 1, 2, 3, 4].filter((x) => x !== epos);
    const keys = new Set();
    const state = {
        cp: [0, 0, 0, 0, 0], co: [0, 0, 0, 0, 0],
        ep: [0, 0, 0, 0, 0], eo: [0, 0, 0, 0, 0],
    };
    state.cp[cpos] = 4;
    state.co[cpos] = c;
    state.ep[epos] = 4;
    state.eo[epos] = e;

    for (const pc of PERMS) {
        for (let i = 0; i < 4; i++) state.cp[cornerPos[i]] = pc[i];
        const cpParity = parity(state.cp);
        for (const pe of PERMS) {
            for (let i = 0; i < 4; i++) state.ep[edgePos[i]] = pe[i];
            if (parity(state.ep) !== cpParity) continue;
            for (let t = 0; t < 27; t++) {
                const a = t % 3;
                const b = ((t / 3) | 0) % 3;
                const cc = ((t / 9) | 0) % 3;
                const dd = (30 - c - a - b - cc) % 3;
                state.co[cornerPos[0]] = a;
                state.co[cornerPos[1]] = b;
                state.co[cornerPos[2]] = cc;
                state.co[cornerPos[3]] = dd;
                for (let fl = 0; fl < 8; fl++) {
                    const a2 = fl & 1;
                    const b2 = (fl >> 1) & 1;
                    const c2 = (fl >> 2) & 1;
                    state.eo[edgePos[0]] = a2;
                    state.eo[edgePos[1]] = b2;
                    state.eo[edgePos[2]] = c2;
                    state.eo[edgePos[3]] = (e + a2 + b2 + c2) & 1;
                    keys.add(canonical(state));
                }
            }
        }
    }
    return {
        slug, letter, count: keys.size,
        keys: [...keys].sort((a, b) => a - b).map((x) => x.toString(36)),
    };
}

const ALL = Object.fromEntries(CATS.map((cfg) => {
    const info = enumerateCategory(...cfg);
    return [info.slug, info];
}));

const ALL_COUNT = Object.values(ALL).reduce((sum, info) => sum + info.count, 0);
console.log(`enumerated ${ALL_COUNT.toLocaleString()} cases in ${CATS.length} families`);

const MIRROR_CORNER = [0, 3, 2, 1, 4];
const MIRROR_EDGE = [1, 0, 3, 2, 4];

function mirrorState(state) {
    const cp = [];
    const co = [];
    const ep = [];
    const eo = [];
    for (let n = 0; n < 5; n++) {
        cp[MIRROR_CORNER[n]] = MIRROR_CORNER[state.cp[n]];
        co[MIRROR_CORNER[n]] = (3 - state.co[n]) % 3;
        ep[MIRROR_EDGE[n]] = MIRROR_EDGE[state.ep[n]];
        eo[MIRROR_EDGE[n]] = (state.eo[n] + (n === 4 ? 1 : 0) + (state.ep[n] === 4 ? 1 : 0)) % 2;
    }
    return { cp, co, ep, eo };
}

const FACE_MIRROR = { U: "U", D: "D", F: "R", R: "F", L: "B", B: "L" };

function normalizeAlg(alg) {
    return alg.trim().split(/\s+/).filter(Boolean).map((token) => {
        const m = token.match(/^([URFDLB])(2'?|'|3)?$/);
        if (!m) throw new Error(`Unsupported LSLL token: ${token}`);
        const face = m[1];
        const suffix = m[2];
        if (suffix === "2" || suffix === "2'") return face + "2";
        if (suffix === "'" || suffix === "3") return face + "'";
        return face;
    }).join(" ");
}

function mirrorAlg(alg) {
    return alg.trim().split(/\s+/).filter(Boolean).map((token) => {
        const m = token.match(/^([URFDLB])(2'?|'|3)?$/);
        if (!m) throw new Error(`Unsupported LSLL token: ${token}`);
        const face = FACE_MIRROR[m[1]];
        const suffix = m[2];
        if (suffix === "2" || suffix === "2'") return face + "2";
        if (suffix === "'" || suffix === "3") return face;
        return face + "'";
    }).join(" ");
}

function sleep(ms) {
    return new Promise((resolve) => setTimeout(resolve, ms));
}

async function fetchCase(key) {
    for (let attempt = 0; attempt < 5; attempt++) {
        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), REQUEST_TIMEOUT_MS);
        try {
            const res = await fetch(`https://api.cuberoot.me/v1/alg/lsll/case/${key}`, {
                signal: controller.signal,
            });
            clearTimeout(timer);
            if (res.status === 429) {
                await sleep(500 * (attempt + 1));
                continue;
            }
            if (res.status === 404) return { key, status: "pending" };
            if (!res.ok) throw new Error(`HTTP ${res.status}`);
            const data = await res.json();
            if (data.status === "ok" && Array.isArray(data.algs) && data.algs.length) {
                return { key, status: "ok", alg: data.algs[0] };
            }
            if (data.status === "pending") return { key, status: "pending" };
            return { key, status: "other" };
        } catch {
            clearTimeout(timer);
            if (attempt === 4) return { key, status: "error" };
            await sleep(250 * (attempt + 1));
        }
    }
    return { key, status: "error" };
}

async function mapPool(items, limit, fn) {
    const out = new Array(items.length);
    let cursor = 0;
    const workers = Array.from({ length: limit }, async () => {
        while (true) {
            const index = cursor++;
            if (index >= items.length) return;
            out[index] = await fn(items[index], index);
        }
    });
    await Promise.all(workers);
    return out;
}

async function loadSource(slug) {
    const info = ALL[slug];
    const cachePath = path.join(CACHE, `${slug}.json`);
    if (existsSync(cachePath)) {
        const cached = JSON.parse(await readFile(cachePath, "utf8"));
        if (cached.rows && cached.rows.length === info.count) {
            return cached.rows;
        }
    }

    const results = await mapPool(info.keys, CONCURRENCY, (key) => fetchCase(key));
    const rows = results.filter((r) => r.status === "ok").map((r) => [r.key, r.alg]);
    const pending = results.filter((r) => r.status === "pending").length;
    const errors = results.filter((r) => r.status === "error" || r.status === "other").length;
    console.log(`${slug}: ${rows.length}/${info.count} ok, ${pending} pending, ${errors} errors`);

    if (pending || errors) {
        throw new Error(`${slug} is incomplete; rerun the script (CubeRoot may still be filling it)`);
    }
    await mkdir(CACHE, { recursive: true });
    await writeFile(cachePath, JSON.stringify({ slug, rows }), "utf8");
    return rows;
}

async function buildFamily(slug) {
    const info = ALL[slug];
    const sourceSlug = SOURCE_BY_TARGET[info.letter];
    if (!sourceSlug) throw new Error(`No mirror source for ${info.letter}`);
    const sourceRows = await loadSource(sourceSlug);

    let rows;
    if (sourceSlug === slug) {
        rows = sourceRows.map(([key, alg]) => [key, normalizeAlg(alg)]);
    } else {
        rows = sourceRows.map(([key, alg]) => {
            const state = decodeState(parseInt(key, 36));
            const mirrorKey = canonical(mirrorState(state)).toString(36);
            return [mirrorKey, mirrorAlg(normalizeAlg(alg))];
        });
    }

    rows.sort((a, b) => parseInt(a[0], 36) - parseInt(b[0], 36));
    const expected = new Set(info.keys);
    const seen = new Set();
    for (const [key] of rows) {
        if (seen.has(key)) throw new Error(`${slug} duplicate key ${key}`);
        seen.add(key);
    }
    for (const key of expected) {
        if (!seen.has(key)) throw new Error(`${slug} missing key ${key}`);
    }
    for (const key of seen) {
        if (!expected.has(key)) throw new Error(`${slug} unexpected key ${key}`);
    }
    if (rows.length !== info.count) throw new Error(`${slug} count mismatch`);

    const named = rows.map(([key, alg]) => [`${info.letter} #${key}`, alg]);
    const body = named.map(([name, alg]) => `[${JSON.stringify(name)},${JSON.stringify(alg)}]`).join(",");
    const content = `window.LSLLOneStep=window.LSLLOneStep||{};\nwindow.LSLLOneStep[${JSON.stringify(slug)}]=[${body}];\n`;
    await mkdir(OUT, { recursive: true });
    await writeFile(path.join(OUT, `${slug}.js`), content, "utf8");
    return { slug, count: named.length, bytes: Buffer.byteLength(content) };
}

const targets = CATS
    .map((cfg) => cfg[0])
    .filter((slug) => !ONLY.size || ONLY.has(slug));

const results = [];
for (const slug of targets) {
    results.push(await buildFamily(slug));
}

const total = results.reduce((sum, r) => sum + r.count, 0);
console.log(`wrote ${results.length} families, ${total} formulas, ${Math.round(results.reduce((s, r) => s + r.bytes, 0) / 1024)} KB`);
